// Command genunicode writes src/unicode_tables.rs from Go's unicode package,
// so the Rust lexer classifies characters exactly as msh's does, with the
// same Unicode version (ai/gui-terminal.typ, "The Rust port").
//
// Usage, from gui/msh-editor: go run tools/genunicode/main.go > src/unicode_tables.rs
package main

import (
	"fmt"
	"unicode"
)

func ranges(name, doc string, t *unicode.RangeTable, from rune) {
	fmt.Printf("/// %s\npub(crate) static %s: &[(u32, u32)] = &[\n", doc, name)
	var lo, hi rune = -1, -1
	flush := func() {
		if lo >= 0 {
			fmt.Printf("    (0x%04X, 0x%04X),\n", lo, hi)
		}
	}
	for r := from; r <= unicode.MaxRune; r++ {
		if !unicode.Is(t, r) {
			continue
		}
		if r == hi+1 && lo >= 0 {
			hi = r
			continue
		}
		flush()
		lo, hi = r, r
	}
	flush()
	fmt.Println("];")
}

func main() {
	fmt.Printf("// Generated by tools/genunicode from Go's unicode package (Unicode %s). Do not edit.\n\n", unicode.Version)
	fmt.Printf("pub const UNICODE_VERSION: &str = %q;\n\n", unicode.Version)
	// unicode.IsDigit and IsSpace answer Latin-1 themselves; the tables are
	// what they use above it.
	ranges("DIGIT", "Category Nd above Latin-1: Go's unicode.IsDigit.", unicode.Digit, 0x100)
	fmt.Println()
	ranges("WHITE_SPACE", "White_Space above Latin-1: Go's unicode.IsSpace.", unicode.White_Space, 0x100)
}
