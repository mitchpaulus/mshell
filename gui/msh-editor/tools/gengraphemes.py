"""Write src/grapheme_tables.rs from the uniseg version mshell builds with,
so the Rust editor splits text into graphemes exactly as msh's does (the
same Unicode version; ai/gui-terminal.typ, "The Rust port").

Usage, from gui/msh-editor: python3 -I tools/gengraphemes.py > src/grapheme_tables.rs
"""
import os, re, subprocess

root = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..', '..')
gomod = open(os.path.join(root, 'mshell', 'go.mod')).read()
version = re.search(r'github.com/rivo/uniseg (v\S+)', gomod).group(1)
cache = subprocess.run(['go', 'env', 'GOMODCACHE'], capture_output=True, text=True, check=True).stdout.strip()
src = open(os.path.join(cache, f'github.com/rivo/uniseg@{version}', 'graphemeproperties.go')).read()
unicode = re.search(r'Public/(\d+\.\d+\.\d+)/', src).group(1)
props = {'Prepend': 2, 'CR': 3, 'LF': 4, 'Control': 5, 'Extend': 6, 'RegionalIndicator': 7, 'SpacingMark': 8,
         'L': 9, 'V': 10, 'T': 11, 'LV': 12, 'LVT': 13, 'ZWJ': 14, 'ExtendedPictographic': 15}
rows = re.findall(r'\{0x([0-9A-F]+), 0x([0-9A-F]+), pr(\w+)\}', src)
print(f'// Generated by tools/gengraphemes.py from github.com/rivo/uniseg {version} (Unicode {unicode}). Do not edit.\n')
print(f'pub const GRAPHEME_UNICODE_VERSION: &str = "{unicode}";\n')
print('/// Grapheme break property by code point range, as uniseg\'s graphemeCodePoints;')
print('/// the numbers are uniseg\'s pr constants.')
print('pub(crate) static GRAPHEME_PROPERTIES: &[(u32, u32, u8)] = &[')
for lo, hi, p in rows:
    print(f'    (0x{lo}, 0x{hi}, {props[p]}),')
print('];')
